import re

from atlas_engine.brain.models import ReferenceTrajectory, TrajectoryStep
from atlas_engine.codegen.params import ClassifiedParams

_HEADER_TOP = '''"""Golden script — generated by Atlas AI. Deterministic replay only:
no LLM calls, no dependency on the authoring engine at runtime."""

import re
import sys
import time

from playwright.sync_api import sync_playwright


def _page(page, index):
    """Resolves the Nth page of the shared browser context: page 0 is the
    page the run started on; pages 1+ are popups the app opened."""
    if index == 0:
        return page
    deadline = time.time() + 15
    while time.time() < deadline:
        pages = page.context.pages
        if len(pages) > index:
            return pages[index]
        page.wait_for_timeout(200)
    raise TimeoutError(f"Popup page {index} never opened")
'''

# Opt-in per-portal pacing (portal.pacing.preActionMs) — only emitted when
# configured, ported from the previous app's pyEmit.ts PACING_MS/_pace().
_PACE_HELPER_TEMPLATE = '''

PACING_MS = {pre_action_ms}


def _pace(pg):
    # Slow-portal pacing: a human-like pause before every step's action —
    # elements can be clickable before their data/handlers are ready on
    # slow portals, so instant actions land on a half-ready page.
    try:
        pg.wait_for_timeout(PACING_MS)
    except Exception:
        pass
'''

_HEADER_RUN = '''

def run(start_url: str) -> None:
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(headless=True)
        page = browser.new_page()
        page.goto(start_url)

'''

_FOOTER = '''
        browser.close()


if __name__ == "__main__":
    run(sys.argv[1] if len(sys.argv) > 1 else {start_url!r})
'''


_CODEGEN_EXPR_PREFIX = "codegen_expr:"

_PAGE_ROOT_RE = re.compile(r"^(page\d*)\.(.*)$", re.DOTALL)


def _build_review_header(
    trajectory: ReferenceTrajectory, *, portal_name: str, confidence: float | None,
    classified: "ClassifiedParams",
) -> str:
    """Banner comment matching the previous app's Stage-5 review header —
    computed live from the trajectory + classification, no new stored state
    needed beyond what's already on PortalProfile/TrajectoryStep."""
    warnings = []
    no_value_indices = [p.step_index for p in classified.params if not p.default_value]
    if no_value_indices:
        ids = ", ".join(str(i) for i in no_value_indices)
        warnings.append(
            f"#  - {len(no_value_indices)} fill step(s) have no captured/parameterized value "
            f"(PHI redaction): {ids}"
        )
    if any(s.expects_popup for s in trajectory.steps):
        warnings.append(
            "#  - This flow opens at least one new page/popup — the trigger step is a judgment call, not a certainty."
        )
    confidence_str = f"{confidence}" if confidence is not None else "unknown"
    lines = [
        "# ==============================================================================",
        f"# GENERATED by Atlas AI — portal: {portal_name}",
        f"# Source trajectory confidence: {confidence_str}",
    ]
    if warnings:
        lines.append("#")
        lines.append("# REVIEW BEFORE TRUSTING RESULTS:")
        lines.extend(warnings)
    lines.append("# ==============================================================================")
    return "\n".join(lines) + "\n"


# ── visible=true preference ──────────────────────────────────────────────
# Port of the old app's preferVisible(): the brain's runtime resolver always
# prefers the VISIBLE element on a multi-match (hidden-duplicate trap — e.g.
# Waystar's 64× id="Checkbox1"); a frozen `.first` can't, so appending
# `>> visible=true` picks the visible one.  Only for locator()-based (CSS/id/
# structural) selectors — get_by_* go through _emit_locator_call which doesn't
# take the >> filter.  Never for force_click (that step interacts with a
# deliberately-hidden element).  Placed BEFORE any nth suffix.
_NTH_SUFFIX_RE = re.compile(r"^(.*?)(\s*>>\s*nth=\d+)\s*$")


def _prefer_visible(selector: str, force_click: bool) -> str:
    """Mirror the brain's runtime behavior ('act on the VISIBLE match') in
    the static golden.  Ported verbatim from emitGolden.ts preferVisible()."""
    if force_click:
        return selector
    if "visible=true" in selector:
        return selector
    # codegen_expr: selectors use get_by_* which don't take >> filters
    if selector.startswith(_CODEGEN_EXPR_PREFIX):
        return selector
    m = _NTH_SUFFIX_RE.match(selector)
    if m:
        return f"{m.group(1)} >> visible=true{m.group(2)}"
    return f"{selector} >> visible=true"


# ── session-random ID detection ──────────────────────────────────────────
# Port of the old app's looksSessionRandom(): an id with a trailing token of
# 6+ alphanumerics containing a digit, or any 3+ digit run, is common for
# session-random ids (#search__input__id_jnm8z6qetrg, #ctl00_12345).
# Conservative: a false positive only costs falling back to the (proven
# cross-session) next candidate; a false negative freezes an id that breaks.

def _looks_session_random(id_value: str) -> bool:
    """Ported verbatim from emitGolden.ts looksSessionRandom()."""
    if re.search(r"\d{3,}", id_value):
        return True
    tail = id_value.rsplit("_", 1)[-1].rsplit("-", 1)[-1]
    return len(tail) >= 6 and bool(re.search(r"\d", tail)) and bool(re.fullmatch(r"[a-zA-Z0-9]+", tail))


def _best_selector(step: TrajectoryStep) -> str:
    """Pick the best selector from a step's candidates, skipping session-random
    IDs (which break across sessions) and applying visible=true for CSS selectors
    that might match hidden duplicates.  Ported from emitGolden.ts's selector
    selection + preferVisible + looksSessionRandom logic."""
    ranked = sorted(step.selector_candidates, key=lambda c: c["rank"])
    for cand in ranked:
        sel = cand["selector"]
        # Skip session-random bare #id selectors — fall to the next candidate
        if sel.startswith("#") and _looks_session_random(sel.lstrip("#")):
            continue
        return sel
    # All candidates were session-random — use the first one anyway
    return ranked[0]["selector"]


def _emit_locator_gesture(call: str, step: TrajectoryStep) -> list[str]:
    """Per-gesture lines for an already-resolved Playwright receiver chain
    `call` (e.g. `page` or `_page(page, 1).locator('#q').content_frame`).
    Mirrors the reference brain runner's do_gesture exactly: hover reveals and
    typed input pause, press keys fall back to Enter, force_click is honored."""
    if step.kind == "click":
        return [f"{call}.click(force=True)" if step.force_click else f"{call}.click()"]
    if step.kind == "dblclick":
        return [f"{call}.dblclick()"]
    if step.kind == "hover":
        return [f"{call}.hover()", "        page.wait_for_timeout(900)"]
    if step.kind == "hover_click":
        return [f"{call}.hover()", "        page.wait_for_timeout(900)", f"{call}.click()"]
    if step.kind == "dispatch_click":
        return [f'{call}.dispatch_event("click")']
    if step.kind == "fill":
        return [f"{call}.fill({step.value!r})"]
    if step.kind == "type":
        return [f"{call}.click()", f"{call}.fill('')", f"{call}.press_sequentially({step.value or ''!r}, delay=100)"]
    if step.kind == "press":
        return [f"{call}.press({(step.key or step.value or 'Enter')!r})"]
    if step.kind == "check":
        return [f"{call}.check()"]
    if step.kind == "uncheck":
        return [f"{call}.uncheck()"]
    if step.kind == "select_option":
        return [f"{call}.select_option({step.value!r})"]
    raise ValueError(f"Unsupported step kind for emission: {step.kind}")


def _emit_locator_call(expr: str, step: TrajectoryStep) -> list[str]:
    """Emits the codegen locator chain as real Playwright calls, resolving
    the page root (`page` or `page1`, ...) to the right object."""
    m = _PAGE_ROOT_RE.match(expr)
    if not m:
        root, rest = "page", expr
    else:
        root, rest = m.group(1), m.group(2)
    receiver = f"_page(page, {int(root[4:])})" if root != "page" else "page"
    return _emit_locator_gesture(f"{receiver}.{rest}", step)


def _emit_css_step(selector: str, step: TrajectoryStep) -> list[str]:
    """Emit a step that uses a plain CSS selector.  The selector has ALREADY
    been run through _prefer_visible by _emit_step, so it may contain
    >> visible=true — use page.locator() which supports the >> filter."""
    # When the selector contains >> visible=true (or any >> filter), we MUST use
    # page.locator(sel) because page.click(sel) etc. do not support >> filters.
    use_locator = ">>" in selector
    if use_locator:
        call = f"page.locator({selector!r}).first"
        return _emit_locator_gesture(call, step)
    if step.kind == "click":
        return [f"page.click({selector!r}{', force=True' if step.force_click else ''})"]
    if step.kind == "dblclick":
        return [f"page.dblclick({selector!r})"]
    if step.kind == "hover":
        return [f"page.hover({selector!r})", "        page.wait_for_timeout(900)"]
    if step.kind == "hover_click":
        return [f"page.hover({selector!r})", "        page.wait_for_timeout(900)", f"page.click({selector!r})"]
    if step.kind == "dispatch_click":
        return [f'page.locator({selector!r}).dispatch_event("click")']
    if step.kind == "fill":
        return [f"page.fill({selector!r}, {step.value!r})"]
    if step.kind == "type":
        return [f"page.click({selector!r})", f"page.fill({selector!r}, '')", f"page.press_sequentially({selector!r}, {step.value or ''!r}, delay=100)"]
    if step.kind == "press":
        return [f"page.press({selector!r}, {(step.key or step.value or 'Enter')!r})"]
    if step.kind == "check":
        return [f"page.check({selector!r})"]
    if step.kind == "uncheck":
        return [f"page.uncheck({selector!r})"]
    if step.kind == "select_option":
        return [f"page.select_option({selector!r}, {step.value!r})"]
    raise ValueError(f"Unsupported step kind for emission: {step.kind}")


def _emit_step(step: TrajectoryStep, *, pre_action_ms: int = 0, settle_after_nav_ms: int = 0) -> str:
    selector = _best_selector(step)
    if step.kind == "goto":
        lines = [f"page.goto({selector!r})"]
    elif step.kind == "click_xy":
        lines = [f"page.mouse.click({step.x or 0}, {step.y or 0})"]
    elif selector.startswith(_CODEGEN_EXPR_PREFIX):
        lines = _emit_locator_call(selector[len(_CODEGEN_EXPR_PREFIX):], step)
    elif step.kind in (
        "click", "dblclick", "hover", "hover_click", "dispatch_click",
        "fill", "type", "press", "check", "uncheck", "select_option",
    ):
        # Apply visible=true preference for CSS selectors (ported from
        # emitGolden.ts preferVisible) — handles hidden-duplicate trap.
        selector = _prefer_visible(selector, step.force_click)
        lines = _emit_css_step(selector, step)
    else:
        raise ValueError(f"Unsupported step kind for emission: {step.kind}")

    if step.expected_effect == "url_changed":
        lines.append('page.wait_for_load_state("domcontentloaded")')

    # Slow-portal settle (opt-in, portal.pacing.settleAfterNavMs): after a
    # navigation specifically, wait (capped) for the network to go quiet
    # before the next step — matches the previous app's pyEmit.ts. Adaptive:
    # a timeout here is swallowed, never fails the script.
    if settle_after_nav_ms > 0 and step.kind == "goto":
        lines.append("try:")
        lines.append(f'    page.wait_for_load_state("networkidle", timeout={settle_after_nav_ms})')
        lines.append("except Exception:")
        lines.append("    pass")

    body = "\n".join(f"        {line}" for line in lines)

    if pre_action_ms > 0:
        # Slow-portal pacing (opt-in, portal.pacing.preActionMs) — called
        # before EVERY step's action, unconditionally, like the previous
        # app's per-step pyEmit.ts emission.
        body = "        _pace(page)\n" + body

    return body


def _build_argparse_and_main_params(classified: "ClassifiedParams") -> str:
    """Generates the argparse setup + params-dict construction spliced into
    the emitted script's main(). One --<kebab-name> CLI flag per classified
    CliParam (default = recorded value, still overridable); secrets are
    NEVER CLI flags — always read from an env var, so a real credential
    never appears as a command-line argument (visible in shell history/
    process listings) or a literal in the script file."""
    lines = ["    parser = argparse.ArgumentParser()"]
    for p in classified.params:
        attr = p.cli_name.replace("-", "_")
        lines.append(f'    parser.add_argument("--{p.cli_name}", default="{p.default_value}")')
    lines.append('    parser.add_argument("--headless", action="store_true", default=True)')
    lines.append('    parser.add_argument("--headed", dest="headless", action="store_false")')
    lines.append('    parser.add_argument("--diagnostics-dir", default="diagnostics")')
    lines.append('    parser.add_argument("--batch", default="")')
    lines.append("    args = parser.parse_args()")
    lines.append("")
    lines.append("    params = {}")
    for s in classified.secrets:
        lines.append(f'    params["{s.label}"] = os.environ.get("{s.env_var}", "")')
    for p in classified.params:
        attr = p.cli_name.replace("-", "_")
        lines.append(f'    params["{attr}"] = args.{attr}')
    lines.append('    params["headless"] = args.headless')
    lines.append('    params["diagnostics_dir"] = args.diagnostics_dir')
    return "\n".join(lines)


def emit_golden_script(
    trajectory: ReferenceTrajectory, *, start_url: str,
    pre_action_ms: int = 0, settle_after_nav_ms: int = 0,
) -> str:
    """Deterministic, no LLM — converts a verified trajectory into a
    self-contained Playwright script with zero atlas_engine dependency.
    pre_action_ms/settle_after_nav_ms are opt-in per-portal pacing (both
    default to 0/absent, which emits byte-for-byte the same script as
    before this feature existed)."""
    body = "\n".join(
        _emit_step(step, pre_action_ms=pre_action_ms, settle_after_nav_ms=settle_after_nav_ms)
        for step in trajectory.steps
    )
    header = _HEADER_TOP
    if pre_action_ms > 0:
        header += _PACE_HELPER_TEMPLATE.format(pre_action_ms=pre_action_ms)
    header += _HEADER_RUN
    return header + body + "\n" + _FOOTER.format(start_url=start_url)