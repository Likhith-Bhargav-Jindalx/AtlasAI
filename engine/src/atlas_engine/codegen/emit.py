from atlas_engine.brain.models import ReferenceTrajectory, TrajectoryStep

_HEADER = '''"""Golden script — generated by Atlas AI. Deterministic replay only:
no LLM calls, no dependency on the authoring engine at runtime."""

import sys

from playwright.sync_api import sync_playwright


def run(start_url: str) -> None:
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(headless=True)
        page = browser.new_page()
        page.goto(start_url)

'''

_FOOTER = '''
        browser.close()


if __name__ == "__main__":
    run(sys.argv[1] if len(sys.argv) > 1 else {start_url!r})
'''


def _selector(step: TrajectoryStep) -> str:
    return sorted(step.selector_candidates, key=lambda c: c["rank"])[0]["selector"]


def _emit_step(step: TrajectoryStep) -> str:
    selector = _selector(step)
    if step.kind == "click":
        line = f"page.click({selector!r})"
    elif step.kind == "fill":
        line = f"page.fill({selector!r}, {step.value!r})"
    else:
        raise ValueError(f"Unsupported step kind for emission: {step.kind}")

    if step.expected_effect == "url_changed":
        line += '\n        page.wait_for_load_state("domcontentloaded")'
    return f"        {line}"


def emit_golden_script(trajectory: ReferenceTrajectory, *, start_url: str) -> str:
    """Deterministic, no LLM — converts a verified trajectory into a
    self-contained Playwright script with zero atlas_engine dependency."""
    body = "\n".join(_emit_step(step) for step in trajectory.steps)
    return _HEADER + body + "\n" + _FOOTER.format(start_url=start_url)
